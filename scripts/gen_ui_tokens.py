"""Generate material_boot/ui/web/tokens.css: the Material 3 Expressive colour roles of the editor from one seed (forest green by default), light and dark.
usage: python3 scripts/gen_ui_tokens.py [#RRGGBB]     (the colour science vendored in material_boot/_vendor, or a pip materialyoucolor)"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from materialyoucolor.dynamiccolor.dynamic_color import DynamicColor  # noqa: E402
from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors as M  # noqa: E402
from materialyoucolor.hct import Hct  # noqa: E402
from materialyoucolor.scheme.scheme_expressive import SchemeExpressive  # noqa: E402

from material_boot import palette  # noqa: E402,F401  (puts the vendored materialyoucolor on the path when pip has none)

seed = (sys.argv[1] if len(sys.argv) > 1 else "#0B3D2E").upper()


def kebab(n):
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), n)


def roles(dark):
    s = SchemeExpressive(Hct.from_int(0xFF000000 | int(seed[1:], 16)), dark, 0.0)
    out = {}
    for name in dir(M):
        v = getattr(M, name)
        if isinstance(v, DynamicColor) and not name.startswith(("_", "highest")):
            out[kebab(name)] = "#%06X" % (v.get_hct(s).to_int() & 0xFFFFFF)
    return out


def block(sel, r):
    return sel + " {\n" + "\n".join(f"  --c-{k}: {v};" for k, v in sorted(r.items())) + "\n}\n"


light, dark = roles(False), roles(True)
css = f"""/* generated by scripts/gen_ui_tokens.py from the seed {seed} (Material 3 Expressive). Do not edit by hand. */
{block(":root", light)}
@media (prefers-color-scheme: dark) {{
{block(":root:not([data-theme='light'])", dark)}}}
{block(":root[data-theme='dark']", dark)}"""
(ROOT / "material_boot/ui/web/tokens.css").write_text(css)
print("wrote material_boot/ui/web/tokens.css with", len(light), "roles, seed", seed)
